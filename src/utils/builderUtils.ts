/**
 * Resolves a guaranteed, sharp, official SVG/CDN logo for any developer in the catalog.
 * Strict brand isolation: A builder is NEVER assigned another developer's logo.
 */
export const resolveBuilderLogo = (builder?: { 
    id?: string; 
    slug?: string; 
    name?: string; 
    logo?: string; 
} | null): string => {
    if (!builder) return '';

    const id = (builder.id || '').toLowerCase().trim();
    const slug = (builder.slug || '').toLowerCase().trim().replace(/^b-/, '');
    const name = (builder.name || '').toLowerCase().trim();

    // 1. Direct ID match
    if (id && VERIFIED_BUILDER_LOGOS[id]) {
        return VERIFIED_BUILDER_LOGOS[id];
    }

    // 2. Direct Slug match
    if (slug && VERIFIED_BUILDER_LOGOS[slug]) {
        return VERIFIED_BUILDER_LOGOS[slug];
    }

    // 3. Fallback to builder.logo if valid
    if (builder.logo && 
        !builder.logo.includes('keystoneliv.com') && 
        !builder.logo.includes('example.com') && 
        builder.logo.trim() !== '') {
        return builder.logo;
    }

    // 4. Fuzzy slug match
    for (const [key, logoUrl] of Object.entries(VERIFIED_BUILDER_LOGOS)) {
        if (key.length > 3 && (slug.includes(key) || key.includes(slug))) {
            return logoUrl;
        }
    }

    return '';
};
