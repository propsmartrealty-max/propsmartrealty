import json, re, os

print("Generating Edge SEO In-Memory Database for Cloudflare Pages Functions...")

# 1. Read projectSummaries.ts
with open('src/data/projectSummaries.ts', 'r') as f:
    text = f.read()
m_proj = re.search(r'export const PROJECT_SUMMARIES:\s*Project\[\]\s*=\s*(\[.*?\]);', text, re.DOTALL)
projects = json.loads(m_proj.group(1))

# 2. Read mockData.ts for builders and localities
with open('src/data/mockData.ts', 'r') as f:
    mock_text = f.read()

m_b = re.search(r'export const BUILDERS:\s*Builder\[\]\s*=\s*(\[.*?\]);\s*export', mock_text, re.DOTALL)
builders = json.loads(m_b.group(1))
builder_name_map = {b['id']: b['name'] for b in builders}

m_l = re.search(r'export const LOCATIONS:\s*Locality\[\]\s*=\s*(\[.*?\]);\s*export', mock_text, re.DOTALL)
localities = json.loads(m_l.group(1))

# 3. Create compact data structures
edge_projects = {}
for p in projects:
    slug = p.get('slug') or p.get('id')
    bid = p.get('builderId')
    bname = builder_name_map.get(bid, '')
    edge_projects[slug] = {
        't': p.get('title'),
        'b': bname,
        'l': p.get('location'),
        'c': p.get('city', 'Pune'),
        'p': p.get('exactPrice') or p.get('priceRange') or 'Price on Request',
        'r': p.get('reraId') or 'A031262401295',
        'i': p.get('heroImage') or p.get('image'),
        'd': (p.get('description') or '')[:250].replace('\n', ' ').strip(),
        'cf': (p.get('configurations') or [])[:3]
    }

edge_builders = {}
for b in builders:
    slug = b.get('slug') or b.get('id')
    clean_slug = re.sub(r'^b-', '', slug)
    edge_builders[slug] = {
        'n': b.get('name'),
        'l': b.get('logo') or 'https://propsmart.co.in/images/propsmart-logo.png',
        'd': (b.get('description') or '')[:250].replace('\n', ' ').strip()
    }
    if slug != clean_slug:
        edge_builders[clean_slug] = edge_builders[slug]

edge_localities = {}
for loc in localities:
    slug = loc.get('slug') or loc.get('id')
    edge_localities[slug] = {
        'n': loc.get('name'),
        'c': loc.get('city', 'Pune'),
        'p': loc.get('avgPriceSqft')
    }

ts_content = f"""// Auto-generated by scripts/generate_edge_seo_index.py
// Pre-computed in-memory SEO dictionary for instant Edge SSR HTML rewrites across 300+ Cloudflare Edge POPs.

export interface EdgeProjectInfo {{
    t: string; // title
    b?: string; // builderName
    l: string; // location
    c: string; // city
    p: string; // price
    r: string; // rera
    i: string; // image
    d: string; // desc
    cf: string[]; // configs
}}

export interface EdgeBuilderInfo {{
    n: string; // name
    l: string; // logo
    d: string; // desc
}}

export interface EdgeLocalityInfo {{
    n: string; // name
    c: string; // city
    p?: number; // avgPriceSqft
}}

export const EDGE_PROJECTS: Record<string, EdgeProjectInfo> = {json.dumps(edge_projects, indent=2)};

export const EDGE_BUILDERS: Record<string, EdgeBuilderInfo> = {json.dumps(edge_builders, indent=2)};

export const EDGE_LOCALITIES: Record<string, EdgeLocalityInfo> = {json.dumps(edge_localities, indent=2)};
"""

os.makedirs('functions', exist_ok=True)
with open('functions/edgeSeoData.ts', 'w') as f:
    f.write(ts_content)

print(f"✅ Generated functions/edgeSeoData.ts: {len(edge_projects)} projects, {len(edge_builders)} builders, {len(edge_localities)} localities.")
